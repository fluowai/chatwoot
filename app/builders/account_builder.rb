# frozen_string_literal: true

class AccountBuilder
  include CustomExceptions::Account
  pattr_initialize [:account_name, :email!, :confirmed, :user, :user_full_name, :user_password, :super_admin, :locale]

  def perform
    if @user.nil?
      validate_email
      validate_user
    end
    ActiveRecord::Base.transaction do
      @account = create_account
      @user = create_and_link_user
    end
    [@user, @account]
  rescue StandardError => e
    Rails.logger.debug e.inspect
    raise e
  end

  private

  def user_full_name
    # the empty string ensures that not-null constraint is not violated
    @user_full_name || ''
  end

  def account_name
    # the empty string ensures that not-null constraint is not violated
    @account_name || ''
  end

  def validate_email
    Account::SignUpEmailValidationService.new(@email).perform
  end

  def validate_user
    if User.exists?(email: @email)
      raise UserExists.new(email: @email)
    else
      true
    end
  end

  def create_account
    default_locale = (@locale.presence || ENV.fetch('DEFAULT_LOCALE', 'pt_BR')).to_s.tr('-', '_')
    available = LANGUAGES_CONFIG.values.pluck(:iso_639_1_code)
    resolved_locale = available.include?(default_locale) ? default_locale : I18n.locale.to_s
    default_timezone = ENV.fetch('DEFAULT_TIMEZONE', 'America/Sao_Paulo')

    @account = Account.create!(
      name: account_name,
      locale: resolved_locale,
      reporting_timezone: ActiveSupport::TimeZone[default_timezone].present? ? default_timezone : nil,
      custom_attributes: { 'onboarding_step' => 'account_details' }
    )
    Current.account = @account
  end

  def create_and_link_user
    if @user.present? || create_user
      link_user_to_account(@user, @account)
      @user
    else
      raise UserErrors.new(errors: @user.errors)
    end
  end

  def link_user_to_account(user, account)
    AccountUser.create!(
      account_id: account.id,
      user_id: user.id,
      role: AccountUser.roles['administrator']
    )
  end

  def create_user
    @user = build_user
    @user.save!
  end

  def build_user
    @user = User.new(email: @email,
                     password: user_password,
                     password_confirmation: user_password,
                     name: user_full_name)
    @user.type = 'SuperAdmin' if @super_admin
    @user.confirm if @confirmed
    @user
  end
end
